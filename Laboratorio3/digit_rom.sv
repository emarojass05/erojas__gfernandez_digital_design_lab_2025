        ROM[62] = 8'b01111110; ROM[63] = 8'b00000000;

        // ===== DÍGITO 4 =====
        ROM[64] = 8'b00000100; ROM[65] = 8'b00001100;
        ROM[66] = 8'b00010100; ROM[67] = 8'b00100100;
        ROM[68] = 8'b01000100; ROM[69] = 8'b10000100;
